def polarity_index() -> dict[str, tuple[float, int]]:
    """word -> (weight, polarity)。polarity: +1 正 / -1 负。"""
    index: dict[str, tuple[float, int]] = {}
    for word, weight in POSITIVE_LEXICON.items():
        index[word] = (weight, 1)
    for word, weight in NEGATIVE_LEXICON.items():
        index[word] = (weight, -1)
    return index


def lexicon_size() -> dict[str, int]:
    return {
        "positive": len(POSITIVE_LEXICON),
        "negative": len(NEGATIVE_LEXICON),
        "degree": len(DEGREE_ADVERBS),
        "negator": len(NEGATORS),
        "rhetorical": len(RHETORICAL_MARKERS),
    }
